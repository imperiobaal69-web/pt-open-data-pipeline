"""Outputs: Parquet exports of the marts, a Mermaid lineage diagram from the
dbt manifest, and a Markdown run summary computed from the warehouse."""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

MARTS = {
    "dim_geography": "geo_level, geo_code",
    "fct_card_purchases_monthly": "geo_code, month",
    "mart_municipality_monthly": "geo_code, month",
    "fct_sector_purchases_monthly": "geo_code, month, sector_code",
    "rpt_series_granularity": "varcd",
}


def export_parquet(db_path: Path, out_dir: Path) -> dict[str, int]:
    out_dir.mkdir(parents=True, exist_ok=True)
    counts = {}
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        for table, order in MARTS.items():
            target = out_dir / f"{table}.parquet"
            con.execute(
                f"copy (select * from marts.{table} order by {order}) "
                f"to '{target.as_posix()}' (format parquet, compression zstd)"
            )
            counts[table] = con.execute(f"select count(*) from '{target.as_posix()}'").fetchone()[0]
    finally:
        con.close()
    (out_dir / "exports.json").write_text(json.dumps(counts, indent=2) + "\n", encoding="utf-8")
    return counts


def lineage_mermaid(manifest_path: Path) -> str:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    layers: dict[str, list[str]] = {"sources": [], "seeds": [], "staging": [], "intermediate": [], "marts": []}
    nodes: dict[str, str] = {}
    for uid, src in manifest["sources"].items():
        nodes[uid] = f"{src['source_name']}.{src['name']}"
        layers["sources"].append(uid)
    edges = set()
    for uid, node in manifest["nodes"].items():
        if node["resource_type"] == "seed":
            nodes[uid] = node["name"]
            layers["seeds"].append(uid)
        elif node["resource_type"] == "model":
            nodes[uid] = node["name"]
            layer = node["fqn"][1] if len(node["fqn"]) > 2 else "marts"
            layers.setdefault(layer, []).append(uid)
            for parent in node["depends_on"]["nodes"]:
                edges.add((parent, uid))

    def ident(uid: str) -> str:
        return nodes[uid].replace(".", "_")

    lines = ["flowchart LR"]
    for layer, uids in layers.items():
        if not uids:
            continue
        lines.append(f"  subgraph {layer}")
        for uid in sorted(uids, key=lambda u: nodes[u]):
            lines.append(f"    {ident(uid)}[{nodes[uid]}]")
        lines.append("  end")
    for parent, child in sorted(edges, key=lambda e: (nodes.get(e[0], e[0]), nodes[e[1]])):
        if parent in nodes:
            lines.append(f"  {ident(parent)} --> {ident(child)}")
    return "\n".join(lines) + "\n"


def write_lineage(manifest_path: Path, out_path: Path) -> None:
    diagram = lineage_mermaid(manifest_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        "# dbt lineage\n\n"
        "Generated by `ptdata docs` from `manifest.json`; do not edit by hand.\n\n"
        f"```mermaid\n{diagram}```\n",
        encoding="utf-8",
    )


def _table(headers: list[str], rows: list[tuple]) -> str:
    def fmt(v: object) -> str:
        if v is None:
            return "–"
        if isinstance(v, float):
            if abs(v) < 1:
                return f"{v:.4f}"
            return f"{v:,.2f}" if abs(v) < 1000 else f"{v:,.0f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)

    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(out)


def pct(column: str, sign: str = "") -> str:
    """SQL expression rendering a fraction as a percentage string (NULL stays NULL)."""
    return f"printf('%{sign}.1f%%', {column} * 100)"


def _dbt_results(run_results_path: Path) -> list[tuple]:
    if not run_results_path.exists():
        return []
    results = json.loads(run_results_path.read_text(encoding="utf-8"))["results"]
    counts: dict[tuple[str, str], int] = {}
    for r in results:
        kind = r["unique_id"].split(".")[0]
        counts[(kind, r["status"])] = counts.get((kind, r["status"]), 0) + 1
    return sorted((k, s, n) for (k, s), n in counts.items())


def write_summary(db_path: Path, run_results_path: Path, out_path: Path, source: str) -> str:
    con = duckdb.connect(str(db_path), read_only=True)
    q = lambda sql: con.execute(sql).fetchall()  # noqa: E731
    try:
        raw_files, raw_bytes = q("select count(*), sum(bytes) from raw.extract_manifest")[0]
        counts = [
            ("raw.ine_observations", q("select count(*) from raw.ine_observations")[0][0]),
            ("staging.stg_ine__observations", q("select count(*) from staging.stg_ine__observations")[0][0]),
        ] + [(f"marts.{t}", q(f"select count(*) from marts.{t}")[0][0]) for t in MARTS]
        granularity = q(
            """
            select varcd, measure, breakdown, first_month::varchar, last_month::varchar, months_published,
                   finest_geography, geographies_published, municipalities_published,
                   breakdown_categories_published, observations_loaded, observations_missing_value
            from marts.rpt_series_granularity order by breakdown, measure
            """
        )
        latest = q("select max(month) from marts.fct_card_purchases_monthly")[0][0]
        national = q(
            f"""
            select month::varchar, spend_eur::bigint, transactions::bigint, avg_ticket_eur::double,
                   {pct("online_share")}, {pct("foreign_card_share")}
            from marts.fct_card_purchases_monthly
            where geo_code = 'PT' and month in (date '{latest}', cast(date '{latest}' - interval 12 month as date))
            order by month
            """
        )
        top_foreign = q(
            f"""
            select geo_name, nuts3_name, spend_eur::bigint, {pct("foreign_card_share")}, {pct("spend_yoy_change", "+")}
            from marts.mart_municipality_monthly
            where month = date '{latest}'
            order by foreign_card_share desc nulls last, geo_code limit 10
            """
        )
        top_online = q(
            f"""
            select geo_name, nuts3_name, spend_eur::bigint, {pct("online_share")},
                   printf('%+.1f pp', online_share_yoy_diff * 100)
            from marts.mart_municipality_monthly
            where month = date '{latest}'
            order by online_share desc nulls last, geo_code limit 5
            """
        )
        null_growth = q(
            """
            select count(*) filter (where spend_mom_change is null),
                   count(*) filter (where spend_yoy_change is null),
                   count(*)
            from marts.mart_municipality_monthly
            """
        )[0]
        sector_month = q("select max(month) from marts.fct_sector_purchases_monthly")[0][0]
        top_sectors = (
            q(
                f"""
            select sector_code, sector_name, spend_eur::bigint, {pct("share_of_region_spend")}
            from marts.fct_sector_purchases_monthly
            where geo_code = '11A' and month = date '{sector_month}'
            order by spend_eur desc, sector_code limit 5
            """
            )
            if sector_month
            else []
        )
        retrieved = q("select min(retrieved_utc)::varchar, max(retrieved_utc)::varchar from raw.extract_manifest")[0]
    finally:
        con.close()

    parts = [
        f"# Run summary ({source})",
        "",
        "Generated by `ptdata report` from the DuckDB warehouse and dbt's `run_results.json`; do not edit by hand.",
        "",
    ]
    if source == "live":
        parts += [f"Raw responses retrieved from INE between {retrieved[0]} and {retrieved[1]} UTC.", ""]
    else:
        parts += ["Source: committed fixtures (real INE responses for a small set of geographies).", ""]
    parts += [
        f"Raw layer: {raw_files:,} files, {raw_bytes:,} bytes.",
        "",
        "## Row counts",
        "",
        _table(["table", "rows"], counts),
        "",
        "## dbt build results",
        "",
        _table(["resource", "status", "count"], _dbt_results(run_results_path)),
        "",
        "## Granularity by indicator (from INE metadata)",
        "",
        _table(
            [
                "varcd",
                "measure",
                "breakdown",
                "first month",
                "last month",
                "months",
                "finest geography",
                "geographies",
                "municipalities",
                "breakdown categories",
                "obs loaded",
                "obs missing",
            ],
            granularity,
        ),
        "",
        f"## Portugal, {latest} vs. same month a year earlier",
        "",
        _table(
            ["month", "spend (EUR)", "transactions", "avg ticket (EUR)", "online share", "foreign-card share"], national
        ),
        "",
        f"## Highest foreign-card share, municipalities, {latest}",
        "",
        _table(["municipality", "NUTS III", "spend (EUR)", "foreign-card share", "spend YoY"], top_foreign),
        "",
        f"## Highest online share, municipalities, {latest}",
        "",
        _table(
            ["municipality", "NUTS III", "spend (EUR)", "online share", "online share, change vs. year earlier"],
            top_online,
        ),
        "",
        "## Growth columns left NULL because the prior period is not in the data",
        "",
        _table(["MoM NULL", "YoY NULL", "municipality-months"], [null_growth]),
        "",
    ]
    if top_sectors:
        parts += [
            f"## Área Metropolitana do Porto (NUTS III 11A), top CAE sections, {sector_month}",
            "",
            _table(["CAE", "section", "spend (EUR)", "share of region"], top_sectors),
            "",
        ]
    text = "\n".join(parts)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8")
    return text
