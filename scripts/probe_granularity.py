"""Probe what the INE card-spend series refuse to break down by (live API).

Writes reports/granularity_probe.md. Three checks:
1. The finest geography level in each indicator's metadata.
2. Asking a sector (CAE) indicator for a municipality: INE's answer, verbatim.
3. How sparse the finest published sector detail (CAE subclass x NUTS III) is.

Usage: uv run python scripts/probe_granularity.py
"""

from __future__ import annotations

import datetime as dt
import json
import urllib.request
from collections import Counter
from pathlib import Path

from ptdata import ine
from ptdata.catalog import load_catalog
from ptdata.transport import USER_AGENT, HttpTransport

OUT = Path(__file__).resolve().parents[1] / "reports" / "granularity_probe.md"
LEVEL_NAMES = {1: "country", 2: "NUTS I", 3: "NUTS II", 4: "NUTS III", 5: "municipality"}
PORTO_MUNICIPALITY = "11A1312"
PORTO_METRO_NUTS3 = "11A"


def raw_get(url: str) -> dict:
    """Plain GET that returns the payload even when INE reports failure."""
    req = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=240) as r:
        doc = json.loads(r.read().decode("utf-8"))
    return doc[0] if isinstance(doc, list) else doc


def main() -> None:
    http = HttpTransport()
    lines = [
        "# Granularity probe (live INE API)",
        "",
        "Generated by `scripts/probe_granularity.py`; do not edit by hand.",
        f"Run on {dt.datetime.now(dt.UTC).strftime('%Y-%m-%d %H:%M')} UTC.",
        "",
        "## 1. Finest geography in each indicator's metadata",
        "",
        "| varcd | breakdown | geography levels published | finest | breakdown categories |",
        "|---|---|---|---|---|",
    ]
    metas = {}
    for s in load_catalog():
        meta = ine.parse_payload(http.get(ine.meta_url(s.varcd)))
        metas[s.varcd] = meta
        levels = Counter(int(c["categ_nivel"]) for c in ine.categories(meta, "2"))
        published = ", ".join(f"{LEVEL_NAMES[k]} ({v})" for k, v in sorted(levels.items()))
        lines.append(
            f"| {s.varcd} | {s.breakdown} | {published} | {LEVEL_NAMES[max(levels)]} | "
            f"{len(ine.categories(meta, '3')):,} |"
        )
    lines += [
        "",
        "No indicator's geography dimension (NUTS 2024) has a level below the municipality, "
        "so parish (freguesia) figures are not published for any of these series.",
        "",
    ]

    sector = next(s for s in load_catalog() if s.breakdown == "sector")
    latest = ine.monthly_periods(metas[sector.varcd])[-1]
    url = ine.data_url(sector.varcd, [latest], geos=[PORTO_MUNICIPALITY], breakdown=["TOT"])
    answer = raw_get(url)
    status = answer.get("Sucesso", {})
    message = (status.get("Falso") or status.get("Verdadeiro") or [{}])[0].get("Msg", "")
    lines += [
        "## 2. Sector indicator requested for a municipality",
        "",
        f"Request: `{url}`",
        "",
        f'INE answer: success = {"Verdadeiro" in status}, message = "{message}"',
        "",
    ]

    subclasses = {c["categ_cod"] for c in ine.categories(metas[sector.varcd], "3") if c["categ_nivel"] == "6"}
    # Listing the 915 subclass codes in Dim3 makes INE fail (ORA-06502, buffer
    # too small), so request every category and keep the subclasses.
    doc = ine.parse_payload(http.get(ine.data_url(sector.varcd, [latest], geos=[PORTO_METRO_NUTS3])))
    records = [r for recs in doc["Dados"].values() for r in recs if r["dim_3"] in subclasses]
    values = [r.get("valor") for r in records]
    numeric = [float(v) for v in values if v not in (None, "") and v.replace(".", "", 1).lstrip("-").isdigit()]
    zeros = sum(1 for v in numeric if v == 0)
    non_numeric = len(values) - len(numeric)
    lines += [
        "## 3. Finest published sector detail: CAE subclass x NUTS III",
        "",
        f"Indicator {sector.varcd}, {ine.parse_month_code(latest):%Y-%m}, NUTS III {PORTO_METRO_NUTS3} "
        f"(Área Metropolitana do Porto), {len(subclasses):,} CAE subclasses requested.",
        "",
        "| cells returned | zero | non-numeric (unavailable) | positive |",
        "|---|---|---|---|",
        f"| {len(values):,} | {zeros:,} | {non_numeric:,} | {len(numeric) - zeros:,} |",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
